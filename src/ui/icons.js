const cache = new Map();
export function iconURL(name) {
  if (cache.has(name)) return cache.get(name);
  const d = ICONS[name] || ICONS.info;
  let rects = '';
  d.r.forEach((row, y) => {
    const r = (row + '................').slice(0, 16);
    for (let x = 0; x < 16; ) {
      const ch = r[x];
      let n = 1;
      while (x + n < 16 && r[x + n] === ch) n++;
      if (ch !== '.' && d.p[ch]) rects += `<rect x="${x}" y="${y}" width="${n + 0.02}" height="1.02" fill="${d.p[ch]}"/>`;
      x += n;
    }
  });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">${rects}</svg>`;
  const url = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
  cache.set(name, url);
  return url;
}

export function icon(name, cls = '') {
  return `<img class="ic ${cls}" src="${iconURL(name)}" alt="" draggable="false">`;
}

